export interface Texts {
    t: (key: StringKey, ...args: (string | number)[]) => string;
    status: (code: number | null) => string;
    evaluation: (key: string) => string;
    region: (key: string) => string;
    isDanish: boolean;
}

export function texts(languageId: number): Texts {
    const isDanish = languageId === 1030;
    const dict = isDanish ? da : en;
    return {
        isDanish,
        t: (key, ...args) => dict[key].replace(/\{(\d+)\}/g, (_m: string, i: string) => String(args[Number(i)] ?? "")),
        status: code => code === null ? "" : `${code.toString().padStart(2, "0")} ${(isDanish ? statusDa : statusEn)[code] ?? ""}`,
        evaluation: key => (isDanish ? evalDa : evalEn)[key] ?? key,
        region: key => (isDanish ? regionDa : regionEn)[key] ?? key
    };
}
